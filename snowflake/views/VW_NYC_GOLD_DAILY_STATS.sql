create or replace view NYC_TAXI_DB.REPORT.VW_NYC_GOLD_DAILY_STATS(
	PICKUP_DATE,
	TOTAL_TRIPS,
	TOTAL_PASSENGERS,
	AVG_PASSENGERS_PER_TRIP,
	TOTAL_DISTANCE,
	AVG_TRIP_DISTANCE,
	TOTAL_TRIP_DURATION_MINUTES,
	AVG_TRIP_DURATION_MINUTES,
	TOTAL_FARE,
	AVG_FARE,
	TOTAL_TIPS,
	AVG_TIP,
	AVG_TIP_PERCENTAGE,
	TOTAL_REVENUE,
	AVG_REVENUE_PER_TRIP,
	AVG_SPEED_MPH,
	REVENUE_PER_MILE,
