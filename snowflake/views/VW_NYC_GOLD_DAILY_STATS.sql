AVG_TIP,
AVG_TIP_PERCENTAGE,
TOTAL_REVENUE,
AVG_REVENUE_PER_TRIP,
AVG_SPEED_MPH,
REVENUE_PER_MILE,
REVENUE_PER_MINUTE,
PROCESSING_TIMESTAMP,
PREV_DAY_TRIPS,
TRIP_GROWTH_PCT,
ROLLING_7D_AVG_TRIPS,
PROCESSING_TS
